import { chromium, request } from 'playwright-core';
import assert from 'node:assert/strict';
import { access, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const base = process.env.SQL_STUDIO_DEPLOY_BASE;
assert.ok(base && process.env.SQL_STUDIO_DEPLOY_USER && process.env.SQL_STUDIO_DEPLOY_PASSWORD, 'Supply deployment URL and credentials through environment variables');
const output = process.env.SQL_STUDIO_VERIFY_OUT || '../../target/sql-studio-metadata-production';
await mkdir(output, { recursive: true });
const client = await request.newContext({ baseURL: base, timeout: 30000 });
const report = { sqlExecuted: false, modelInvoked: false, metadataReads: 0 };
let browser, projectId, headers;
try {
  const login = await client.post('/api/v1/enterprise/auth/login', { data: { username: process.env.SQL_STUDIO_DEPLOY_USER, password: process.env.SQL_STUDIO_DEPLOY_PASSWORD } });
  assert.equal(login.status(), 200);
  const session = (await login.json()).data;
  headers = { Authorization: 'Bearer ' + session.token, 'X-Workspace-Id': 'data-science' };
  const health = await client.get('/api/v1/health', { headers });
  assert.equal(health.status(), 200); assert.equal((await health.json()).data.status, 'UP'); report.health = 'UP';
  const workspace = await client.get('/api/v1/workspaces/data-science/manifest', { headers });
  assert.equal(workspace.status(), 200);
  const manifest = (await workspace.json()).data.manifest;
  assert.equal(manifest.name, '数据车间');
  assert.equal(manifest.description, '一站式完成数据接入、Python 开发、SQL / ETL 加工与脚本发布。');
  report.workspaceName = manifest.name; report.workspaceConfigVersion = manifest.configVersion;
  const created = await client.post('/api/v1/data-science/sql/projects', { headers, data: { name: '__schema_pagination_verify_' + Date.now(), dialect: 'spark' } });
  assert.equal(created.status(), 200); projectId = (await created.json()).data.id;
  const file = await client.put(`/api/v1/data-science/sql/projects/${projectId}/files`, { headers, data: { path: 'sql/verify.sql', kind: 'SQL', content: '-- Deployment verification: metadata browsing only.\nSELECT 1;', expectedVersion: 0 } });
  assert.equal(file.status(), 200);
  const denied = await client.get(`/api/v1/data-science/sql/projects/${projectId}/metadata/providers`);
  assert.equal(denied.status(), 401); report.unauthenticatedMetadataDenied = true;
  let executablePath;
  for (const candidate of ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe']) {
    try { await access(candidate); executablePath = candidate; break; } catch {}
  }
  assert.ok(executablePath, 'Local Chromium required');
  browser = await chromium.launch({ executablePath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1560, height: 980 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().includes('/metadata/') && response.url().endsWith('/operations')) report.metadataReads++; });
  await page.addInitScript(value => localStorage.setItem('chatchat.auth.session', JSON.stringify(value)), session);
  await page.goto(base + '/#/w/data-science/sqlStudio', { waitUntil: 'domcontentloaded' });
  await page.locator('.sql-ide-shell').waitFor({ timeout: 45000 });
  await page.getByLabel('SQL 工程', { exact: true }).selectOption(projectId);
  await page.locator('.sql-tree-file button[title="sql/verify.sql"]').click();
  await page.getByRole('button', { name: '数据库', exact: true }).click();
  const explorer = page.locator('.sql-schema-explorer');
  await explorer.locator('select').nth(1).locator('option').nth(1).waitFor({ state: 'attached' });
  const asset = await explorer.locator('select').nth(1).locator('option').nth(1).getAttribute('value');
  await explorer.locator('select').nth(1).selectOption(asset);
  await explorer.getByRole('treeitem').first().waitFor({ timeout: 45000 });
  const pager = explorer.getByLabel('元数据分页');
  const ready = () => page.waitForFunction(() => document.querySelector('.sql-schema-tables')?.getAttribute('aria-busy') === 'false');
  await ready();
  report.totalTables = Number((await pager.locator('.sql-schema-page-summary > span').textContent()).match(/\d+/)[0]);
  assert.ok(report.totalTables > 50, 'Registered source must provide real multi-page metadata');
  assert.equal(await explorer.getByRole('treeitem').count(), 50);
  await pager.getByRole('button', { name: '下一页', exact: true }).click(); await ready();
  assert.ok((await pager.locator('nav span').textContent()).startsWith('2 /'));
  const tableNames = () => explorer.locator('[aria-label^="展开 "]').evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')));
  const secondPage = await tableNames();
  await explorer.locator('[aria-label^="展开 "]').first().click(); await ready();
  const fields = await explorer.getByRole('group').textContent();
  await page.setViewportSize({ width: 1280, height: 720 });
  const list = explorer.getByRole('tree');
  await list.evaluate(el => { el.scrollTop = 160; });
  const position = await list.evaluate(el => el.scrollTop);
  assert.ok(position > 0);
  const listBox = await list.boundingBox(), pagerBox = await pager.boundingBox();
  assert.ok(listBox.y + listBox.height <= pagerBox.y + 1, 'Table content cannot cover the pager');
  assert.ok(pagerBox.y + pagerBox.height <= 720, 'Pager must be visible in short viewports');
  await page.locator('.monaco-editor').first().click({ position: { x: 180, y: 80 } });
  assert.deepEqual(await tableNames(), secondPage);
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  assert.equal(await explorer.getByRole('group').textContent(), fields);
  await page.evaluate(() => window.dispatchEvent(new Event('focus'))); await ready();
  assert.deepEqual(await tableNames(), secondPage);
  assert.equal(await explorer.getByRole('group').textContent(), fields);
  assert.equal(await list.evaluate(el => el.scrollTop), position);
  assert.ok((await pager.locator('nav span').textContent()).startsWith('2 /'));
  await page.getByRole('button', { name: '工程文件', exact: true }).click();
  await page.getByRole('button', { name: '数据库', exact: true }).click();
  assert.equal(await explorer.getByRole('group').textContent(), fields);
  report.retainedPageFieldsAndScroll = true; report.fixedPagerAt1280x720 = true;
  await page.screenshot({ path: path.join(output, 'schema-page-2-production.png'), fullPage: true });
  await pager.getByRole('button', { name: '上一页', exact: true }).click(); await ready();
  assert.ok((await pager.locator('nav span').textContent()).startsWith('1 /'));
  await explorer.getByLabel('每页表数量').selectOption('20'); await ready();
  assert.equal(await explorer.getByRole('treeitem').count(), 20);
  await pager.getByRole('button', { name: '下一页', exact: true }).click(); await ready();
  assert.equal(await explorer.getByRole('treeitem').count(), 20);
  assert.ok((await pager.locator('nav span').textContent()).startsWith('2 /'));
  report.pageSize20AndNextPrevious = true;
  await explorer.getByLabel('每页表数量').selectOption('100'); await ready();
  assert.equal(await explorer.getByRole('treeitem').count(), Math.min(report.totalTables, 100));
  assert.ok((await pager.locator('nav span').textContent()).startsWith('1 /'));
  report.pageSize100 = true;
  assert.deepEqual(errors, []); report.browserErrors = errors.length;
  report.status = 'PASS';
} finally {
  await browser?.close();
  if (projectId) {
    const cleanup = await client.delete('/api/v1/data-science/sql/projects/' + projectId, { headers });
    report.temporaryProjectRemoved = cleanup.status() === 200;
    assert.ok(report.temporaryProjectRemoved, 'Remove the temporary verification project');
  }
  await writeFile(path.join(output, 'verification.json'), JSON.stringify(report, null, 2));
  await client.dispose();
}
console.log(JSON.stringify(report));
