-- News owns these four JPA tables. Market's dedicated storage remains inside MCP.
-- New installations only; the deployment entry never applies this file to an existing database.
CREATE TABLE IF NOT EXISTS news_source (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  capability_id BIGINT NOT NULL DEFAULT 1,
  source_code VARCHAR(64) NOT NULL UNIQUE, source_name VARCHAR(128) NOT NULL,
  source_type VARCHAR(32) NOT NULL, entry_url VARCHAR(2000) NOT NULL,
  allowed_domain VARCHAR(255), schedule_cron VARCHAR(128), enabled BOOLEAN NOT NULL,
  configuration_json VARCHAR(8000), last_cursor VARCHAR(2000),
  last_collected_at TIMESTAMP(6) WITH TIME ZONE,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS news_source_rule (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_id BIGINT NOT NULL UNIQUE,
  list_selector VARCHAR(1000), link_selector VARCHAR(1000), title_selector VARCHAR(1000),
  content_selector VARCHAR(1000), author_selector VARCHAR(1000), publish_time_selector VARCHAR(1000),
  url_pattern VARCHAR(1000), updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS news_collect_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_id BIGINT NOT NULL,
  source_url VARCHAR(2000) NOT NULL, url_hash VARCHAR(64) NOT NULL UNIQUE, content_hash VARCHAR(64),
  publish_time TIMESTAMP(6) WITH TIME ZONE, collect_status VARCHAR(32) NOT NULL,
  analysis_status VARCHAR(32) NOT NULL, document_id VARCHAR(128),
  collected_at TIMESTAMP(6) WITH TIME ZONE, error_message VARCHAR(4000)
);
CREATE INDEX IF NOT EXISTS idx_news_collect_record_collected_at ON news_collect_record(collected_at);
CREATE TABLE IF NOT EXISTS news_analysis_task (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, document_id VARCHAR(128) NOT NULL UNIQUE,
  source_id BIGINT NOT NULL, status VARCHAR(32) NOT NULL,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  error_message VARCHAR(4000)
);
