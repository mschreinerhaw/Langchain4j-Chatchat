// Uses normal authentication and real metadata/publication APIs. No route interception or SQL execution.
import { createRequire } from 'node:module';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const require = createRequire(resolve('chatchat-api/web-app/package.json'));
const { chromium } = require('playwright-core');
const required = name => { if (!process.env[name]) throw Error(`Set ${name}`); return process.env[name]; };
const base = required('SQL_PUBLICATION_BASE_URL');
const session = JSON.parse(readFileSync(required('SQL_PUBLICATION_SESSION_FILE'), 'utf8'));
const output = resolve(required('SQL_PUBLICATION_OUTPUT_DIR'));
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--no-proxy-server'] });
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
  await context.addInitScript(value => localStorage.setItem('chatchat.auth.session', JSON.stringify(value)), session.data || session);
  const page = await context.newPage(), errors = [], checks = {};
  page.on('pageerror', error => errors.push(error.message));
  const check = (name, valid) => { checks[name] = !!valid; if (!valid) throw Error(name); };
  await page.goto(base + '/#/w/data-science/sqlStudio');
  await page.getByLabel('SQL 工程', { exact: true }).selectOption(required('SQL_PUBLICATION_PROJECT_ID'));
  await page.getByRole('button', { name: process.env.SQL_PUBLICATION_FILE_NAME || 'publication.sql', exact: false }).first().click();
  check('unifiedProjectResources', await page.locator('.sql-resource-tabs').count() === 0);
  check('advancedSettingsCollapsed', await page.locator('.sql-chat-settings').getAttribute('open') === null);
  const source = page.getByLabel('选择数据源', { exact: true });
  await source.selectOption(required('SQL_WORKBENCH_ASSET_REF'));
  const namespace = page.getByLabel('选择数据库或 Schema', { exact: true });
  await namespace.selectOption(required('SQL_WORKBENCH_NAMESPACE'));
  await page.locator('.sql-schema-tables [role=treeitem]').first().waitFor();
  check('optionalTablesRemainUnselected', await page.locator('.sql-schema-tables input:checked').count() === 0);
  await page.getByRole('button', { name: '切换 AI 工程助手', exact: true }).click();
  check('sameContextInNavigation', await page.locator('.sql-resource-sidebar').getByLabel('选择数据源', { exact: true }).inputValue() === process.env.SQL_WORKBENCH_ASSET_REF);
  await page.getByRole('button', { name: '切换 AI 工程助手', exact: true }).click();
  check('singleSourceSelector', await source.count() === 1);
  await page.getByRole('button', { name: '发布为 MCP 模板', exact: true }).click();
  const panel = page.getByRole('dialog', { name: '发布 MCP SQL 模板' });
  await panel.locator('select').first().selectOption(required('SQL_PUBLICATION_REVISION_ID'));
  await panel.getByText('SQL 与发布历史', { exact: true }).waitFor();
  check('realPublishedTestRestored', (await panel.innerText()).includes('SQL_DATABASE_EXECUTION'));
  await panel.getByRole('button', { name: '关闭', exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 800 });
  const scroll = page.locator('.sql-assistant-scroll');
  await scroll.evaluate(element => { element.scrollTop = 0; });
  const height = await scroll.evaluate(element => element.clientHeight);
  check('conversationHasUsableHeight', height >= 200);
  const save = await page.getByRole('button', { name: '保存文件', exact: true }).boundingBox();
  check('saveActionWithinViewport', save && save.x >= 0 && save.x + save.width <= 1280);
  await page.screenshot({ path: resolve(output, 'workbench-final-1280.png'), fullPage: true });
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.screenshot({ path: resolve(output, 'workbench-final.png'), fullPage: true });
  check('noBrowserErrors', errors.length === 0);
  const result = { status: 'PASSED', realBackend: true, businessReadOnly: true, checks, conversationHeightAt1280: height, pageErrors: errors };
  writeFileSync(resolve(output, 'final-build-verification.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally { await browser.close(); }
